//! Declares the app's own commands to Tauri's permission system (needed because installed builds serve the
//! interface from localhost, which counts as a remote page). The list is read from `generate_handler!` in
//! src/lib.rs, and permissions/app-commands.toml grants all of them to the app's window.
use std::fmt::Write;

/// The Apple Music developer token for official releases (LT_MUSICKIT_TOKEN), stored scrambled so it isn't
/// sitting in the program as readable text. Empty when the variable isn't set (everyday builds).
fn musickit_token() {
    println!("cargo:rerun-if-env-changed=LT_MUSICKIT_TOKEN");
    let token = std::env::var("LT_MUSICKIT_TOKEN").unwrap_or_default();
    let seed = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_nanos()).unwrap_or(1) as u64 | 1;
    let mut x = seed;
    let mask: Vec<u8> = (0..token.len().max(1))
        .map(|_| {
            // xorshift64: a different mask for every build
            x ^= x << 13;
            x ^= x >> 7;
            x ^= x << 17;
            (x >> 24) as u8
        })
        .collect();
    let scrambled: Vec<u8> = token.bytes().zip(&mask).map(|(b, m)| b ^ m).collect();
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out.join("musickit_token.bin"), scrambled).expect("write musickit_token.bin");
    std::fs::write(out.join("musickit_mask.bin"), mask).expect("write musickit_mask.bin");
}

fn main() {
    musickit_token();
    println!("cargo:rerun-if-changed=src/lib.rs");
    let src = std::fs::read_to_string("src/lib.rs").expect("src/lib.rs");
    let start = src.find("generate_handler![").expect("generate_handler! in src/lib.rs") + "generate_handler![".len();
    let end = start + src[start..].find(']').expect("closing ] of generate_handler!");
    let commands: Vec<&'static str> = src[start..end]
        .split(',')
        .map(|c| c.trim().rsplit("::").next().unwrap_or("").trim())
        .filter(|c| !c.is_empty())
        .map(|c| &*Box::leak(c.to_string().into_boxed_str()))
        .collect();

    let mut toml = String::from("# Generated by build.rs from generate_handler! in src/lib.rs. Do not edit.\n[[permission]]\nidentifier = \"app-commands\"\ndescription = \"Every command the Lute & Tavern interface uses.\"\ncommands.allow = [\n");
    for c in &commands {
        let _ = writeln!(toml, "  \"{c}\",");
    }
    toml.push_str("]\n");
    std::fs::create_dir_all("permissions").expect("permissions dir");
    if std::fs::read_to_string("permissions/app-commands.toml").ok().as_deref() != Some(&toml) {
        std::fs::write("permissions/app-commands.toml", toml).expect("write permissions/app-commands.toml");
    }

    let commands: &'static [&'static str] = Box::leak(commands.into_boxed_slice());
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(commands)))
        .expect("tauri build");
}
